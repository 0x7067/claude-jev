#!/usr/bin/env python3
"""Default Claude Code vs claude-jev, measured on real transcripts.

  compact   every compact_boundary in ~/.claude/projects is a paired sample:
            the transcript records what the built-in summarizer injected
            (postTokens, durationMs, the summary itself, the preserved tail);
            replaying the same pre-boundary blocks through compactor.judge
            shows what Jev would have injected instead. Post-boundary tool
            calls that re-fetch files or commands already fetched before
            compaction mark context the agent still needed — each approach is
            scored on whether its injected context still contained them.

  router    joins the shipped variant's cached predictions (eval/data) to the
            behavior that actually followed each prompt: on prompts Jev would
            have steered to "no tools needed", the observed tool calls are the
            work the hint would have prevented.

Only ~6 real boundaries exist in a typical transcript set, so --synth adds
synthetic cut points: sessions whose judge-visible content passes ~100k
chars with at least 30 blocks of conversation structure (the range the real
boundaries fired at) get a boundary there, and the default side is a
summary generated by `claude -p` over the same flattened conversation — a
replica of the internal routine, labeled as such.

The router side reuses predictions already computed by replay.py — no API
calls. The compact side calls Jev once per event (cached in
eval/data/compact_cache.jsonl; re-runs are free). Synthetic events also
cache the generated summary — claude -p is only called on first run.
"""

from __future__ import annotations

import argparse
import collections
import concurrent.futures
import hashlib
import json
import os
import random
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts"))
import compactor  # noqa: E402
import prompt_router  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
COMPACT_CACHE = os.path.join(DATA, "compact_cache.jsonl")
DATASET = os.path.join(DATA, "dataset.jsonl")
PREDICTIONS = os.path.join(DATA, "pred_v7_no_unclear.jsonl")
PROJECTS = os.path.expanduser("~/.claude/projects")

CONTINUED = "continued from a previous conversation"
FILE_TOOLS = {"Read", "Edit", "Write", "MultiEdit", "NotebookEdit", "NotebookRead"}
SKIP_TOOLS = {"Task", "TaskCreate", "TaskUpdate", "TaskList", "TaskGet", "TodoWrite"}

# Real boundaries fired at 102-305k flattened chars (recorded preTokens
# 162-200k — the gap is thinking blocks and tool/system overhead block_text
# drops). 100k sits at the bottom of that range — the smallest sessions in
# which compaction is a real scenario. A synthetic cut needs enough session
# left after it for the re-fetch signal to mean anything.
SYNTH_CHARS = 100_000
MIN_POST_RETRIEVALS = 5
# A cut also needs conversation structure: a single giant pasted document
# crosses SYNTH_CHARS in one block, but with nothing to select there is no
# compaction to compare. 30 blocks ≈ a real exchange, well past PIN_TAIL.
MIN_BLOCKS = 30

SUMMARY_PROMPT = """Your task is to create a detailed summary of the conversation so far between a user and an AI coding assistant, paying close attention to the user's explicit requests and the assistant's previous actions. This summary should be thorough in capturing technical details, code patterns, and architectural decisions that would be essential for continuing development work without losing context.

Cover: the primary request and intent; key technical concepts; files and code sections examined or modified, with paths; errors encountered and how they were resolved; problem-solving approaches; pending tasks; and the current state of the work.

CONVERSATION:
"""


# --- shared transcript bits -------------------------------------------------

def tool_key(name: str, inp: dict) -> str | None:
    """A re-fetchable identity for a tool call: same key later = the agent
    went back for something it already had."""
    if name in SKIP_TOOLS:
        return None
    if name in FILE_TOOLS:
        p = inp.get("file_path") or inp.get("notebook_path")
        return f"file:{os.path.normpath(p)}" if p else None
    if name == "Grep":
        p = inp.get("path") or inp.get("pattern")
        return f"grep:{p}" if p else None
    if name == "Glob":
        p = inp.get("pattern")
        return f"glob:{p}" if p else None
    if name == "Bash":
        cmd = (inp.get("command") or "").strip().splitlines()
        return f"bash:{cmd[0].strip()[:120]}" if cmd else None
    if name == "WebFetch":
        u = inp.get("url")
        return f"url:{u}" if u else None
    return None


# Post-compaction, only retrievals count as re-fetches: re-editing a file is
# continuation work, re-reading it is context the compaction dropped.
REFETCH_KINDS = ("file", "grep", "glob", "url")


def tool_calls(lines, lo: int, hi: int) -> list[dict]:
    """Every tool_use in lines[lo:hi] with its line index, name, and key."""
    out = []
    for i in range(lo, hi):
        l = lines[i]
        if len(l) > 2_000_000:
            continue
        try:
            d = json.loads(l)
        except ValueError:
            continue
        if d.get("isSidechain") or d.get("type") != "assistant":
            continue
        content = (d.get("message") or {}).get("content")
        for b in content if isinstance(content, list) else []:
            if isinstance(b, dict) and b.get("type") == "tool_use":
                name = b.get("name", "")
                k = tool_key(name, b.get("input") or {})
                if k:
                    out.append({"i": i, "name": name, "key": k})
    return out


def refetches(pre: list[dict], post: list[dict]) -> list[str]:
    """Post-cut retrieval calls for artifacts fetched pre-cut — context the
    session needed again. The agent's own edits count as fetched artifacts:
    a kept digest can hold the edit block just like the read block."""
    fetched = {c["key"] for c in pre}
    return [c["key"] for c in post
            if c["key"].split(":", 1)[0] in REFETCH_KINDS and c["key"] in fetched]


def key_terms(key: str) -> list[str]:
    """Strings whose presence in an injected context means the artifact's
    location survived: the full path and its basename for files."""
    kind, _, val = key.partition(":")
    terms = [val]
    if kind == "file":
        base = os.path.basename(val)
        if base != val:
            terms.append(base)
    return terms


def covered(key: str, context: str) -> bool:
    return any(t in context for t in key_terms(key))


# --- compact ----------------------------------------------------------------

def boundaries(lines) -> list[dict]:
    """Every compaction event in one transcript: boundary line index, its
    metadata, the injected summary, and the preserved tail's text."""
    by_uuid = {}
    for i, l in enumerate(lines):
        try:
            d = json.loads(l)
        except ValueError:
            continue
        if d.get("uuid"):
            by_uuid[d["uuid"]] = d
    out = []
    for i, l in enumerate(lines):
        try:
            d = json.loads(l)
        except ValueError:
            continue
        if d.get("subtype") != "compact_boundary":
            continue
        meta = d.get("compactMetadata") or {}
        summary = ""
        for j in range(i + 1, min(i + 4, len(lines))):
            try:
                n = json.loads(lines[j])
            except ValueError:
                continue
            c = (n.get("message") or {}).get("content")
            if isinstance(c, str) and CONTINUED in c:
                summary = c
                break
        preserved = "\n".join(
            compactor.block_text((by_uuid[u].get("message") or {}).get("content"))
            for u in (meta.get("preservedMessages") or {}).get("uuids", [])
            if u in by_uuid
        )
        out.append({"i": i, "meta": meta, "summary": summary, "preserved": preserved})
    return out


def load_compact_cache() -> dict:
    cache = {}
    if os.path.exists(COMPACT_CACHE):
        with open(COMPACT_CACHE, errors="replace") as f:
            for line in f:
                try:
                    d = json.loads(line)
                except ValueError:
                    continue
                cache[d["key"]] = d
    return cache


def replay(pre_lines, cache: dict, cache_f, gen=None) -> tuple[list[str], dict, str | None]:
    """Replay Jev's selection on the exact lines a boundary compacted. `gen`
    is a thunk producing the default-side summary — called only on a cache
    miss and stored with the judgment so re-runs skip both APIs."""
    key = hashlib.sha256("".join(pre_lines).encode()).hexdigest()
    if key in cache:
        d = cache[key]
        return d["kept"], d["stats"], d.get("summary")
    with tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False) as tf:
        tf.writelines(pre_lines)
        tmp = tf.name
    try:
        kept, stats = compactor.judge(tmp, None)
    finally:
        os.unlink(tmp)
    summary = gen() if gen else None
    if stats.get("judged"):
        cache[key] = {"key": key, "kept": kept, "stats": stats, "summary": summary}
        if cache_f:
            cache_f.write(json.dumps(cache[key]) + "\n")
            cache_f.flush()
    return kept, stats, summary


def flatten(lines, hi: int) -> str:
    """The conversation as flat text — the summarizer's input."""
    parts = []
    for l in lines[:hi]:
        try:
            d = json.loads(l)
        except ValueError:
            continue
        if d.get("isSidechain") or d.get("type") not in ("user", "assistant"):
            continue
        t = compactor.block_text((d.get("message") or {}).get("content")).strip()
        if t:
            parts.append(t)
    return "\n\n".join(parts)


def tail_text(lines, hi: int, n: int = 6) -> str:
    """The last n content blocks verbatim — the preserved-tail equivalent
    the default side carries alongside its summary."""
    texts = []
    for l in reversed(lines[:hi]):
        try:
            d = json.loads(l)
        except ValueError:
            continue
        if d.get("type") not in ("user", "assistant"):
            continue
        t = compactor.block_text((d.get("message") or {}).get("content")).strip()
        if t:
            texts.append(t)
            if len(texts) >= n:
                break
    return "\n".join(reversed(texts))


def synth_cut(lines) -> int | None:
    """First index where judge-visible content passes SYNTH_CHARS with
    enough retrieval work left after it, or None. The cut is a virtual
    boundary between lines: lines[:cut] is the pre-context the judge sees,
    lines[cut:] the session that follows."""
    total = blocks = 0
    cut = None
    for i, l in enumerate(lines):
        if len(l) > 2_000_000:
            continue
        try:
            d = json.loads(l)
        except ValueError:
            continue
        # compactor.visible_text — same rules transcript_blocks applies.
        # Content the judge can't see can't qualify the cut.
        text = compactor.visible_text(d)
        if text is None:
            continue
        total += len(text)
        blocks += 1
        if total >= SYNTH_CHARS and blocks >= MIN_BLOCKS:
            cut = i + 1
            break
    if cut is None:
        return None
    post = tool_calls(lines, cut, len(lines))
    n = sum(1 for c in post if c["key"].split(":", 1)[0] in REFETCH_KINDS)
    return cut if n >= MIN_POST_RETRIEVALS else None


def gen_summary(conversation: str, model: str) -> str | None:
    """The default side's summary for a synthetic cut, via claude -p."""
    try:
        r = subprocess.run(
            ["claude", "-p", "--model", model, SUMMARY_PROMPT],
            input=conversation, capture_output=True, text=True, timeout=600)
        return r.stdout.strip() or None
    except Exception:
        return None


def cmd_compact(args) -> int:
    files = sorted(
        f for f in
        (os.path.join(dp, fn) for dp, _dn, fns in os.walk(PROJECTS) for fn in fns)
        if f.endswith(".jsonl")
    )
    cache = load_compact_cache()
    cache_f = open(COMPACT_CACHE, "a")
    real, synth, skipped = [], [], []
    real_todo = []

    def analyze(fp, lines, i, end, prev_i, ev, kind):
        pre = tool_calls(lines, prev_i + 1, i)
        # Real events: i is the boundary line itself. Synth: i is the first
        # post-cut line — the virtual boundary sits between i-1 and i.
        post = tool_calls(lines, i + (1 if kind == "real" else 0), end)
        reads = refetches(pre, post)
        summary = None
        if kind == "real":
            kept, stats, _ = replay(lines[:i], cache, cache_f)
            default_ctx = ev["summary"] + "\n" + ev["preserved"]
            meta = ev["meta"]
            # Same basis as the jev digest: injected content, not the whole
            # rebuilt context postTokens records (system+tool overhead is
            # common to both paths).
            post_tokens = len(default_ctx) // 4
            duration_s = round((meta.get("durationMs") or 0) / 1000, 1)
            trigger = meta.get("trigger")
        else:
            gen = lambda: gen_summary(flatten(lines, i), args.model)
            kept, stats, summary = replay(lines[:i], cache, cache_f, gen)
            default_ctx = (summary or "") + "\n" + tail_text(lines, i)
            post_tokens = len(default_ctx) // 4
            duration_s = None
            trigger = "synth"
        # The pure /jev:compact path applies nothing under the MIN_REDUCTION
        # gate — a gated digest's coverage is what the session actually got.
        gated = stats.get("reduction", 0) < compactor.MIN_REDUCTION or not kept
        kept = [] if gated else kept
        digest = "\n".join(kept)
        # A truncated block holds the head plus a re-read pointer — coverage
        # at full fidelity means the bytes survived in a non-truncated keep.
        digest_full = "\n".join(t for t in kept if "elided by jev-compact" not in t)
        return {
            "kind": kind,
            "session": fp.split("/")[-2][:48],
            "subagent": "/subagents/" in fp,
            "event_i": i,
            "n_blocks": stats.get("judged", 0) + stats.get("pinned", 0),
            "trigger": trigger,
            "post_tokens": post_tokens,
            "duration_s": duration_s,
            "jev_tokens": 0 if gated else stats.get("est_tokens_after", 0),
            "jev_ms": stats.get("ms", 0),
            "jev_gated": gated,
            "jev_kept": 0 if gated else stats.get("kept", 0),
            "no_summary": kind == "synth" and not summary,
            "refetch_reads": len(reads),
            "refetch_default_covered": sum(1 for k in reads if covered(k, default_ctx)),
            "refetch_jev_covered": sum(1 for k in reads if covered(k, digest)),
            "refetch_jev_full": sum(1 for k in reads if covered(k, digest_full)),
        }

    candidates = []
    for fp in files:
        try:
            lines = open(fp, errors="replace").readlines()
        except OSError:
            continue
        # A standalone subagent transcript flags every line isSidechain —
        # relative to its parent. For its own compaction those are the
        # session's blocks; strip the flag so the replay sees them.
        if "/subagents/" in fp:
            norm = []
            for l in lines:
                try:
                    d = json.loads(l)
                except ValueError:
                    norm.append(l)
                    continue
                d.pop("isSidechain", None)
                norm.append(json.dumps(d) + "\n")
            lines = norm
        evs = boundaries(lines)
        if evs:
            prev = -1
            for n, ev in enumerate(evs):
                end = evs[n + 1]["i"] if n + 1 < len(evs) else len(lines)
                real_todo.append((fp, lines, ev["i"], end, prev, ev, "real"))
                prev = ev["i"]
        else:
            if any(CONTINUED in l for l in lines[:200]):
                skipped.append(fp)
            cut = synth_cut(lines)
            if cut is not None:
                candidates.append((fp, lines, cut, len(lines), -1, None, "synth"))

    if args.synth and len(candidates) > args.synth:
        random.Random(args.seed).shuffle(candidates)
        candidates = candidates[: args.synth]
    elif not args.synth:
        candidates = []

    todo = real_todo + candidates
    done = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = {ex.submit(analyze, *t): t for t in todo}
        for f in concurrent.futures.as_completed(futs):
            fp, _l, _i, _e, _p, _ev, kind = futs[f]
            try:
                (real if kind == "real" else synth).append(f.result())
            except Exception as e:
                print(f"  {kind} event failed in {os.path.basename(fp)}: {e}",
                      file=sys.stderr)
            done += 1
            if done % 5 == 0 or done == len(todo):
                print(f"\r  analyzed {done}/{len(todo)}", end="", file=sys.stderr, flush=True)
    if todo:
        print(file=sys.stderr)
    cache_f.close()

    def report(rows, title, widths, hdr):
        if not rows:
            return
        print(f"\n{title}\n")
        print("  " + "".join(h.ljust(w) for h, w in zip(hdr, widths)))
        print("  " + "-" * sum(widths))
        tot = collections.Counter()
        for r in sorted(rows, key=lambda r: (r["session"], r["event_i"])):
            name = ("⌄ " if r["subagent"] else "") + r["session"]
            print("  " + "".join(str(c).ljust(w) for c, w in zip([
                name[:33], r["post_tokens"], r["duration_s"] or "—",
                r["jev_ms"], r["jev_tokens"],
                f"{r['jev_kept']}{'*' if r['jev_gated'] else ''}",
                r["refetch_reads"], r["refetch_default_covered"],
                r["refetch_jev_covered"], r["refetch_jev_full"],
            ], widths)))
            tot.update({k: r[k] or 0 for k in
                        ("post_tokens", "duration_s", "jev_ms", "jev_tokens",
                         "refetch_reads", "refetch_default_covered",
                         "refetch_jev_covered", "refetch_jev_full")})
            tot["events"] += 1
            tot["gated"] += bool(r["jev_gated"])
            tot["no_summary"] += bool(r.get("no_summary"))
        n = tot["events"]
        print("  " + "-" * sum(widths))
        print(f"  {'TOTAL ' + str(n) + ' events':<34}"
              f"{tot['post_tokens']:<8}{tot['duration_s']:<8.0f}"
              f"{tot['jev_ms']:<9}{tot['jev_tokens']:<8.0f}{'':<7}{tot['refetch_reads']:<8}"
              f"{tot['refetch_default_covered']:<9}{tot['refetch_jev_covered']:<9}"
              f"{tot['refetch_jev_full']:<9}")
        print(f"    per event: default {tot['post_tokens']/n:.0f} tok injected"
              + (f" (+{tot['duration_s']/n:.0f}s summarizing)" if tot['duration_s'] else "")
              + f" vs jev {tot['jev_tokens']/n:.0f} tok (+{tot['jev_ms']/n:.0f}ms judging)")
        if tot["gated"]:
            print(f"    * {tot['gated']} fell under the min-reduction gate — jev applied nothing")
        if tot["no_summary"]:
            print(f"    ! {tot['no_summary']} synthetic events have no summary (claude -p failed)")
        if tot["refetch_reads"]:
            rd = tot["refetch_reads"]
            print(f"    re-reads: {rd} | default still mentioned {tot['refetch_default_covered']} "
                  f"({100*tot['refetch_default_covered']/rd:.0f}%) | jev held "
                  f"{tot['refetch_jev_covered']} ({100*tot['refetch_jev_covered']/rd:.0f}%), "
                  f"{tot['refetch_jev_full']} ({100*tot['refetch_jev_full']/rd:.0f}%) verbatim")

    widths = [34, 8, 8, 9, 8, 7, 8, 9, 9, 9]
    hdr = ["session", "post_tok", "def_s", "jev_ms", "jev_tok", "kept",
           "reread", "cov_def", "cov_jev", "cov_full"]
    print("default compaction vs Jev selection, replayed on the same blocks")
    report(real, f"real compaction events ({len(real)})", widths, hdr)
    report(synth, f"synthetic cuts — default side generated by claude -p "
                  f"{args.model} ({len(synth)})", widths, hdr)
    if skipped:
        print(f"\nskipped {len(skipped)} transcripts whose compaction happened in an "
              "earlier session file (summary present, pre-compact history elsewhere)")

    out = os.path.join(DATA, "compare_compact.jsonl")
    with open(out, "w") as f:
        for r in real + synth:
            f.write(json.dumps(r) + "\n")
    print(f"\nrows -> {out}")
    return 0


# --- router -----------------------------------------------------------------

def cmd_router(args) -> int:
    ds = {}
    with open(DATASET) as f:
        for line in f:
            r = json.loads(line)
            if not r.get("synthetic"):
                ds[r["id"]] = r
    preds = {}
    with open(PREDICTIONS) as f:
        for line in f:
            d = json.loads(line)
            if not d.get("error"):
                preds[d["id"]] = d["answers"]

    rows = []
    for pid, answers in preds.items():
        rec = ds.get(pid)
        if not rec:
            continue
        hint, _ = prompt_router.decide(dict(answers))
        m = re.search(r"intent=(\w+)", hint or "")
        rows.append({
            "id": pid,
            "hint": m.group(1) if m else None,
            "n_tools": rec["n_tools"],
            "label": rec.get("label"),
        })

    hinted = [r for r in rows if r["hint"]]
    chat = [r for r in rows if r["hint"] == "chat"]
    chat_tools = sum(r["n_tools"] for r in chat)
    chat_used = [r for r in chat if r["n_tools"] > 0]
    harmful = [r for r in chat if r["n_tools"] >= 5]

    print(f"router — shipped hints vs what the unhinted agent did next "
          f"({len(rows)} real prompts)\n")
    print(f"  hint fired on          : {len(hinted)} ({100*len(hinted)/len(rows):.0f}%)")
    print(f"  'answer, no tools'     : {len(chat)} prompts")
    if chat:
        print(f"    default Claude used tools anyway on {len(chat_used)} "
              f"({100*len(chat_used)/len(chat):.0f}%), burning {chat_tools} calls "
              f"(mean {chat_tools/len(chat):.1f}/prompt) — work the hint prevents")
        print(f"    ...but {len(harmful)} of those sessions went on to make 5+ calls, "
              f"where the hint is harmful, not saving")
    by_hint = collections.defaultdict(list)
    for r in hinted:
        by_hint[r["hint"]].append(r["n_tools"])
    print("\n  observed tool calls per hinted prompt (default behavior, unhinted):")
    for h, ts in sorted(by_hint.items()):
        print(f"    {h:<8} n={len(ts):<5} mean {sum(ts)/len(ts):.1f}  "
              f"zero-tool {100*sum(1 for t in ts if t == 0)/len(ts):.0f}%")

    out = os.path.join(DATA, "compare_router.jsonl")
    with open(out, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    print(f"\nrows -> {out}")
    return 0


def main() -> int:
    p = argparse.ArgumentParser(prog="compare", description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("compact", help="default compaction vs jev selection on real events")
    c.add_argument("--synth", type=int, default=0,
                   help="add up to N synthetic cut points in long sessions")
    c.add_argument("--model", default="sonnet",
                   help="model for claude -p default-side summaries on synthetic cuts")
    c.add_argument("--seed", type=int, default=0)
    c.add_argument("--workers", type=int, default=6)
    c.set_defaults(fn=cmd_compact)
    r = sub.add_parser("router", help="shipped hints vs observed unhinted behavior")
    r.set_defaults(fn=cmd_router)
    args = p.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
